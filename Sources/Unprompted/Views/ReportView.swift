import SwiftUI

/// The "AI-Generated Daily Report": real numbers from `StatsTracker`, with confident commentary.
struct ReportView: View {
    let stats: StatsTracker
    let name: String
    let mood: Mood
    @State private var daysAgo = 0

    var body: some View {
        let s = stats.stats(daysAgo: daysAgo) ?? DayStats(day: "")
        ScrollView {
            VStack(alignment: .leading, spacing: 18) {
                VStack(alignment: .leading, spacing: 4) {
                    Text("✨ Your AI-Generated Daily Report").font(.title2.bold())
                    Text("Generated by \(name) using 0 GPUs and an unreasonable amount of confidence.")
                        .font(.callout).foregroundStyle(.secondary)
                }
                Picker("Day", selection: $daysAgo) {
                    Text("Today").tag(0)
                    Text("Yesterday").tag(1)
                }
                .pickerStyle(.segmented)
                .labelsHidden()

                if s.activeSeconds == 0 && daysAgo > 0 {
                    Text("No data for that day. I was probably asleep. Or not installed yet.").foregroundStyle(.secondary)
                } else {
                    content(for: s)
                }

                Text("This report was generated by counting things. No AI was harmed, consulted or involved. Keystrokes are a count only; which keys you pressed is never seen.")
                    .font(.caption).foregroundStyle(.secondary)
            }
            .padding(24)
        }
        .background(Color(nsColor: .windowBackgroundColor))
        .frame(width: 520, height: 640)
    }

    @ViewBuilder
    private func content(for s: DayStats) -> some View {
        LazyVGrid(columns: [GridItem(.flexible()), GridItem(.flexible())], spacing: 12) {
            card("⏱️", "Active time", ReportInsights.duration(s.activeSeconds))
            card("⌨️", "Keystrokes", ReportInsights.number(s.keystrokes))
            card("🔀", "App switches", ReportInsights.number(s.appSwitches))
            card("💬", "Questions asked", ReportInsights.number(s.questions))
        }

        if !s.topApps.isEmpty {
            section("Where your time went") {
                let top = Array(s.topApps.prefix(5))
                let longest = max(1, top.first?.seconds ?? 1)
                ForEach(top, id: \.name) { app in
                    HStack {
                        Text(app.name).frame(width: 120, alignment: .leading).lineLimit(1)
                        GeometryReader { geo in
                            RoundedRectangle(cornerRadius: 4)
                                .fill(LinearGradient(colors: [.blue, .purple, .pink], startPoint: .leading, endPoint: .trailing))
                                .frame(width: max(4, geo.size.width * CGFloat(app.seconds) / CGFloat(longest)))
                        }
                        .frame(height: 12)
                        Text(ReportInsights.duration(app.seconds))
                            .font(.caption.monospacedDigit())
                            .frame(width: 70, alignment: .trailing)
                    }
                }
            }
        }

        section("Our relationship") {
            HStack(spacing: 14) {
                stat("💖", "\(s.pets)", "pets")
                stat("🫳", "\(s.pickups)", "pickups")
                stat("🎯", "\(s.throwsCount)", "throws")
                stat("🗑️", "\(s.trashed)", "trashed")
                stat("🙄", "\(s.goAways)", "go-aways")
                if daysAgo == 0 { stat(mood.emoji, String(mood.label.dropFirst(2)), "mood now") }
            }
        }

        section("✨ AI Insights") {
            ForEach(ReportInsights.insights(for: s), id: \.self) { line in
                Label(line, systemImage: "sparkles").labelStyle(.titleAndIcon)
            }
        }

        let stars = ReportInsights.rating(for: s)
        Text("Overall rating: " + String(repeating: "⭐", count: stars) + String(repeating: "☆", count: 5 - stars)
             + "  Would assist again.")
            .font(.headline)
    }

    private func card(_ icon: String, _ title: String, _ value: String) -> some View {
        VStack(alignment: .leading, spacing: 4) {
            Text("\(icon) \(title)").font(.caption).foregroundStyle(.secondary)
            Text(value).font(.title3.bold().monospacedDigit())
        }
        .frame(maxWidth: .infinity, alignment: .leading)
        .padding(12)
        .background(RoundedRectangle(cornerRadius: 10).fill(Color.secondary.opacity(0.1)))
    }

    private func stat(_ icon: String, _ value: String, _ label: String) -> some View {
        VStack {
            Text(icon).font(.title2)
            Text(value).font(.headline.monospacedDigit())
            Text(label).font(.caption).foregroundStyle(.secondary)
        }
    }

    private func section<Content: View>(_ title: String, @ViewBuilder content: () -> Content) -> some View {
        VStack(alignment: .leading, spacing: 8) {
            Text(title).font(.headline)
            content()
        }
    }
}
